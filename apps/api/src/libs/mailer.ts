import { Resend } from "resend";

import {
  EMERGENCY_EMAIL,
  RESEND_API_KEY,
  RESEND_FROM,
} from "../config/config";

const resend = RESEND_API_KEY ? new Resend(RESEND_API_KEY) : null;

// Sends the emergency alert to the clinic owner. Side-effect lives here (§7);
// the emergency agent only decides *that* an alert is warranted. No-ops with a
// log if the recipient/key isn't configured, so a missing env never crashes a call.
export const sendEmergencyAlert = async (input: {
  summary: string;
  patientName?: string;
  message: string;
}): Promise<boolean> => {
  if (!resend || !EMERGENCY_EMAIL) {
    console.warn(
      "[mailer] emergency alert skipped — RESEND_API_KEY or EMERGENCY_EMAIL not set",
    );
    return false;
  }

  const patient = input.patientName ?? "Unknown patient";
  const html = `
    <h2 style="color:#dc2626;margin:0 0 8px">🚨 Emergency alert — OpenClinic AI</h2>
    <p><strong>Patient:</strong> ${patient}</p>
    <p><strong>Summary:</strong> ${input.summary}</p>
    <p><strong>What they said:</strong> ${input.message}</p>
    <hr/>
    <p style="color:#6b7280;font-size:12px">Auto-generated by the OpenClinic AI receptionist.</p>
  `;

  try {
    await resend.emails.send({
      from: RESEND_FROM,
      to: EMERGENCY_EMAIL,
      subject: `🚨 Emergency: ${input.summary}`,
      html,
    });
    return true;
  } catch (error) {
    console.error("[mailer] failed to send emergency alert", error);
    return false;
  }
};
